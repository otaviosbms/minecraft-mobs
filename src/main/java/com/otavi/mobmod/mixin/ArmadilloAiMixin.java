package com.otavi.mobmod.mixin;

import com.otavi.mobmod.entity.traits.ModCreature;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.entity.animal.armadillo.Armadillo;
import net.minecraft.world.entity.animal.armadillo.ArmadilloAi;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable;

/**
 * With no danger around, the vanilla armadillo AI rolls a rolled-up armadillo back out right away (a one-shot behavior
 * of its idle activity, compiled to the lambda targeted here). A sleeping armadillo stays in its shell until it wakes
 * up ({@link com.otavi.mobmod.mob.armadillo.ArmadilloSleep}).
 * <p>
 * Lambda names are generated by the compiler: if a Minecraft update renames it, the mixin fails at startup with a
 * clear error, and the target has to be looked up again (the lambda that calls {@code Armadillo.rollOut}).
 */
@Mixin(ArmadilloAi.class)
public abstract class ArmadilloAiMixin {
    @Inject(method = "lambda$static$2(Lnet/minecraft/server/level/ServerLevel;Lnet/minecraft/world/entity/animal/armadillo/Armadillo;J)Z",
            at = @At("HEAD"), cancellable = true)
    private static void mobmod$stayRolledUpWhileAsleep(ServerLevel level, Armadillo armadillo, long time, CallbackInfoReturnable<Boolean> cir) {
        ModCreature creature = ModCreature.of(armadillo);
        if (creature != null && creature.isAsleep()) {
            cir.setReturnValue(false);
        }
    }
}
